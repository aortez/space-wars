//! Direct-light visibility over canonical copied collision geometry, without a solver.
use super::*;
use engine_core::lighting::{ENDPOINT_TOLERANCE, LightId, LightRay, LightingError, Visibility};

pub const MAX_LIGHT_COLLIDERS: usize = 2048;
pub const MAX_LIGHT_FOOTPRINTS: usize = 2048;
pub const MAX_OPTICAL_EXCLUSIONS: usize = 256;

/// World-space lightweight solid/tissue footprint, updated by its simulation owner.
#[derive(Clone, Copy, Debug)]
pub struct OpaqueFootprint {
    pub id: LightId,
    pub center: Vec2,
    pub radius: f32,
}

/// Per-collider identity. Physics IDs are not reused during a scenario run;
/// the second word encodes role and part, not an organism-wide exclusion.
pub fn light_collider_id(id: ColliderId) -> LightId {
    LightId(
        id.entity.value(),
        ((id.role.value() as u64) << 16) | id.part as u64,
    )
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub struct VisibilityCounters {
    pub rays: u64,
    pub collider_records: u64,
    pub footprint_tests: u64,
}

pub struct LightingVisibility<'a> {
    snapshot: &'a QuerySnapshot,
    counters: std::cell::Cell<VisibilityCounters>,
    footprints: &'a [OpaqueFootprint],
    transparent: &'a [ColliderId],
}

impl QuerySnapshot {
    /// Water and any physical decorative geometry must be explicitly classified
    /// transparent by the host. Sensors are always excluded. UI is never physics.
    /// No geometry or sources are generated by this query adapter.
    pub fn lighting_visibility<'a>(
        &'a self,
        footprints: &'a [OpaqueFootprint],
        transparent: &'a [ColliderId],
    ) -> Result<LightingVisibility<'a>, LightingError> {
        if self.colliders.len() > MAX_LIGHT_COLLIDERS
            || footprints.len() > MAX_LIGHT_FOOTPRINTS
            || transparent.len() > MAX_OPTICAL_EXCLUSIONS
        {
            return Err(LightingError::Capacity);
        }
        if footprints
            .iter()
            .any(|p| !finite_vec2(p.center) || !p.radius.is_finite() || p.radius <= 0.0)
        {
            return Err(LightingError::InvalidInput);
        }
        let mut identities = BTreeSet::new();
        if footprints.iter().any(|p| !identities.insert(p.id)) {
            return Err(LightingError::ConflictingIdentity);
        }
        // Bound shape-dispatch work too. Complex terrain must be partitioned
        // into admitted shapes; an unsupported shape cannot silently pass light.
        let mut remaining = MAX_LIGHT_COLLIDERS;
        fn admit(shape: &dyn rapier2d::parry::shape::Shape, remaining: &mut usize) -> bool {
            if *remaining == 0 {
                return false;
            }
            *remaining -= 1;
            if let Some(compound) = shape.as_compound() {
                return compound
                    .shapes()
                    .iter()
                    .all(|(_, s)| admit(s.as_ref(), remaining));
            }
            let vertices = if let Some(p) = shape.as_convex_polygon() {
                p.points().len()
            } else if let Some(p) = shape.as_polyline() {
                p.vertices().len()
            } else if shape.as_ball().is_some()
                || shape.as_cuboid().is_some()
                || shape.as_capsule().is_some()
            {
                0
            } else {
                return false;
            };
            if vertices > *remaining {
                return false;
            }
            *remaining -= vertices;
            true
        }
        if !self
            .colliders
            .iter()
            .all(|(_, c)| admit(c.shape(), &mut remaining))
        {
            return Err(LightingError::Capacity);
        }
        Ok(LightingVisibility {
            snapshot: self,
            counters: std::cell::Cell::new(VisibilityCounters::default()),
            footprints,
            transparent,
        })
    }
}

mod precise_segment;

/// Coincident rays have no direction to trim. Test containment and distance to
/// the actual boundary instead. Visit compound children separately so contact
/// with one child's boundary cannot exempt another child's opaque interior.
fn coincident_blocks(
    shape: &dyn rapier2d::parry::shape::Shape,
    pose: &Pose,
    point: Vector,
    local_surface: bool,
) -> bool {
    if let Some(compound) = shape.as_compound() {
        return compound.shapes().iter().any(|(child_pose, child)| {
            coincident_blocks(child.as_ref(), &(pose * child_pose), point, local_surface)
        });
    }
    let projection = shape.project_point(pose, point, true);
    // Open shapes such as polylines may report no interior even on the surface.
    if !projection.is_inside && projection.point != point {
        return false;
    }
    if !local_surface {
        return true;
    }
    let boundary_distance = shape.distance_to_point(pose, point, false).abs();
    // Nonfinite backend results cannot establish a safe local exemption.
    !boundary_distance.is_finite() || boundary_distance > ENDPOINT_TOLERANCE
}

fn shape_blocker(
    ray: LightRay,
    id: LightId,
    shape: &dyn rapier2d::parry::shape::Shape,
    pose: &Pose,
) -> Option<f32> {
    if ray.receiver.position == ray.endpoint.position {
        let local_surface = ray.receiver.surface == Some(id) || ray.endpoint.surface == Some(id);
        return coincident_blocks(shape, pose, to_rapier(ray.receiver.position), local_surface)
            .then_some(0.0);
    }
    precise_segment::cast(ray, id, shape, pose)
}

impl LightingVisibility<'_> {
    pub fn counters(&self) -> VisibilityCounters {
        self.counters.get()
    }
}

impl Visibility for LightingVisibility<'_> {
    fn blocker(&self, ray: LightRay) -> Option<LightId> {
        let mut counters = self.counters.get();
        counters.rays = counters.rays.saturating_add(1);
        counters.collider_records = counters
            .collider_records
            .saturating_add(self.snapshot.colliders.len() as u64);
        counters.footprint_tests = counters
            .footprint_tests
            .saturating_add(self.footprints.len() as u64);
        self.counters.set(counters);
        // Stable identity order makes equal-distance diagnostics reproducible.
        let mut hit: Option<(f32, LightId)> = None;
        let mut record = |distance: f32, id: LightId| {
            if hit.is_none_or(|previous| (distance, id) < previous) {
                hit = Some((distance, id));
            }
        };
        for (_, collider) in self.snapshot.colliders.iter() {
            if !collider.is_enabled() || collider.is_sensor() {
                continue;
            }
            let Some(collider_id) = decode_collider(collider.user_data) else {
                continue;
            };
            if self.transparent.contains(&collider_id) {
                continue;
            }
            let id = light_collider_id(collider_id);
            if let Some(distance) = shape_blocker(ray, id, collider.shape(), collider.position()) {
                record(distance, id);
            }
        }
        for footprint in self.footprints {
            let shape = rapier2d::parry::shape::Ball::new(footprint.radius);
            if let Some(distance) = shape_blocker(
                ray,
                footprint.id,
                &shape,
                &Pose::translation(footprint.center.x, footprint.center.y),
            ) {
                record(distance, footprint.id);
            }
        }
        hit.map(|(_, id)| id)
    }
}

